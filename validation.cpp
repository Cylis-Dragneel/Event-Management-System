// ??? Validate all user fields together ???????????????????????????
bool validateUserFields(const string& username, const string& password,
    const string& email, const string& role) {

    bool valid = true;

    if (!isNonEmpty(username, "username"))         valid = false;
    if (!isValidLength(username, "username", 3, 30)) valid = false;

    if (!isNonEmpty(password, "password"))         valid = false;
    if (!isValidLength(password, "password", 6, 50)) valid = false;

    if (!isNonEmpty(email, "email"))               valid = false;
    if (!isValidEmail(email))                      valid = false;

    if (!isValidRole(role))                        valid = false;

    return valid;
}

// ??? Validate all event fields together ??????????????????????????
bool validateEventFields(const string& title, const string& date,
    int capacity) {

    bool valid = true;

    if (!isNonEmpty(title, "title"))               valid = false;
    if (!isValidLength(title, "title", 3, 100))    valid = false;

    if (!isValidDate(date))                        valid = false;

    if (!isPositiveCapacity(capacity))             valid = false;

    return valid;
}

// ??? Validate all venue fields together ??????????????????????????
bool validateVenueFields(const string& name, int capacity) {

    bool valid = true;

    if (!isNonEmpty(name, "name"))                 valid = false;
    if (!isValidLength(name, "name", 2, 100))      valid = false;

    if (!isPositiveCapacity(capacity))             valid = false;

    return valid;
}

// ??? Validate all budget fields together ?????????????????????????
bool validateBudgetFields(const string& category, const string& type,
    double amount, const string& date) {

    bool valid = true;

    if (!isNonEmpty(category, "category"))         valid = false;
    if (!isValidLength(category, "category", 2, 50)) valid = false;

    if (!isValidBudgetType(type))                  valid = false;

    if (!isNonNegativeAmount(amount))              valid = false;

    if (!isValidDate(date))                        valid = false;

    return valid;
}