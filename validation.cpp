// ??? Event status must be one of 4 valid values ??????????????????
bool isValidEventStatus(const string& status) {
    if (status != "Draft" &&
        status != "Published" &&
        status != "Completed" &&
        status != "Cancelled") {
        cerr << "Validation error: invalid event status '"
            << status << "'." << endl
            << "Valid values: Draft, Published, Completed, Cancelled." << endl;
        return false;
    }
    return true;
}

